package org.apache.phoenix.pherf.run;

import static org.junit.Assert.assertEquals;
import static org.junit.Assert.assertNotEquals;
import static org.junit.Assert.assertTrue;

import java.io.File;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.util.ArrayList;
import java.util.Collections;
import java.util.HashSet;
import java.util.List;
import org.apache.phoenix.pherf.configuration.CoGeneration.WalkStrategy;
import org.apache.phoenix.pherf.configuration.DataModel;
import org.apache.phoenix.pherf.configuration.Query;
import org.apache.phoenix.pherf.configuration.Scenario;
import org.apache.phoenix.pherf.configuration.XMLConfigParser;
import org.apache.phoenix.pherf.rules.IndexHash;
import org.apache.phoenix.pherf.rules.RulesApplier;
import org.apache.phoenix.pherf.spi.ConnectionProvider;
import org.apache.phoenix.pherf.workload.cogen.CoGenerator;
import org.apache.phoenix.pherf.workload.cogen.IndexDecoder;
import org.apache.phoenix.pherf.workload.cogen.Walk;
import org.junit.Rule;
import org.junit.Test;
import org.junit.rules.TemporaryFolder;

/**
 * Verifies requirement RQ-182 by executing the Pherf CLI inside a child JVM. When the scenario
 * includes the coGeneration element, every query placeholder in both closed-loop and open-loop runs
 * is populated by the decoder across a single walk pass over the committed rows. Running the same
 * scenario file with the coGeneration element removed produces the statements generated by the
 * standard rule-based generators.
 */
public class CoGenerationRunTest {
  private static final String ELEMENT = "<coGeneration seed=\"11\"/>";
  private static final int ROWS = 20;

  @Rule
  public TemporaryFolder folder = new TemporaryFolder(ChildJvm.targetDir());

  private static File fixture(String name) {
    return new File(ChildJvm.targetDir().getParentFile(), "src/test/resources/cogen/" + name);
  }

  /**
   * Executes Pherf in a child JVM and returns all recorded SQL statements that begin with any of
   * the specified prefixes.
   */
  private List<String> run(File scenarioFile, boolean realClock, List<String> prefixes,
    String... args) throws Exception {
    ChildJvm child = new ChildJvm(folder.newFolder());
    child.register(ConnectionProvider.class, StatementRecorder.class);
    if (realClock) {
      child.systemProperty(ChildRun.REAL_CLOCK, "true");
    }
    List<String> cli = ChildJvm.args(args);
    cli.addAll(ChildJvm.args("-z", "cogen", "-label", "c", "-writerThreadSize", "2",
      "-disableSchemaApply", "-scenarioFile", scenarioFile.getPath()));
    child.runCli(Collections.singletonList(cli));
    List<String> statements = new ArrayList<>();
    for (String line : Records.read(child.record(StatementRecorder.RECORD))) {
      for (String prefix : prefixes) {
        if (line.startsWith(prefix)) {
          statements.add(line);
        }
      }
    }
    return statements;
  }

  /**
   * Computes the ordered sequence of SQL statements produced by a single walk pass of worker 0 of 1
   * across the 20 committed rows.
   */
  private static List<String> onePass(File scenarioFile) throws Exception {
    XMLConfigParser parser = new XMLConfigParser(scenarioFile.getPath());
    Scenario scenario = parser.getDataModels().get(0).getScenarios().get(0);
    IndexDecoder decoder =
      new IndexDecoder(new RulesApplier(parser), scenario, CoGenerator.Settings.of(scenario), null);
    Walk walk = new Walk(IndexHash.columnSeed(11, "#walk"), WalkStrategy.MULTIPLICATIVE, 0, 1);
    String sql = scenario.getQuerySet().get(0).getQuery().get(0).getStatement();
    List<String> statements = new ArrayList<>();
    for (int k = 0; k < ROWS; k++) {
      statements.add(decoder.statement(sql, () -> walk.next(ROWS)));
    }
    return statements;
  }

  /**
   * Verifies that running with -l and -q commits 20 rows during the load phase and executes 20
   * closed-loop read queries that match a single walk pass in exact order.
   */
  @Test
  public void testClosedLoopReadsOnePass() throws Exception {
    File scenarioFile = fixture("cogen_closed_loop.xml");
    List<String> reads = run(scenarioFile, false, Collections.singletonList("SELECT"), "-l", "-q");
    List<String> expected = onePass(scenarioFile);
    assertEquals(expected, reads);
    assertEquals(ROWS, new HashSet<>(reads).size());
  }

  /**
   * Verifies that when the coGeneration element is omitted from the scenario file, both the
   * executed query statements and the EXPLAIN statements generated for reporting match a direct
   * replay of rule-based placeholder substitution seeded with the child clock.
   */
  @Test
  public void testWithoutElementKeepsRules() throws Exception {
    String text = new String(Files.readAllBytes(fixture("cogen_closed_loop.xml").toPath()),
      StandardCharsets.UTF_8);
    assertTrue(text.contains(ELEMENT));
    File scenarioFile = folder.newFile("cogen_rules.xml");
    Files.write(scenarioFile.toPath(), text.replace(ELEMENT, "").getBytes(StandardCharsets.UTF_8));
    List<String> prefixes = new ArrayList<>();
    prefixes.add("SELECT");
    prefixes.add("EXPLAIN ");
    List<String> statements = run(scenarioFile, false, prefixes, "-l", "-q");

    XMLConfigParser parser = new XMLConfigParser(scenarioFile.getPath());
    DataModel model = parser.getDataModels().get(0);
    Scenario scenario = model.getScenarios().get(0);
    Query query = scenario.getQuerySet().get(0).getQuery().get(0);
    RulesApplier rules = new RulesApplier(model, ChildRun.NOW);
    List<String> replay = new ArrayList<>();
    List<String> recorded = new ArrayList<>();
    int selects = 0;
    for (String statement : statements) {
      boolean explain = statement.startsWith("EXPLAIN ");
      selects += explain ? 0 : 1;
      recorded.add(explain ? statement.substring("EXPLAIN ".length()) : statement);
      replay.add(query.getDynamicStatement(rules, scenario));
    }
    assertEquals(ROWS, selects);
    assertEquals(replay, recorded);
    assertNotEquals(onePass(fixture("cogen_closed_loop.xml")), recorded.subList(0, ROWS));
  }

  /**
   * Verifies that running with -q alone on an open-loop scenario using the real clock assumes the
   * 20 rows configured in the scenario as the committed row count when no load phase is run, and
   * that the 20 arrivals read each row exactly once. Because the workers share a single walk, the
   * arrival execution order may vary, while the complete set of read statements remains invariant.
   */
  @Test
  public void testOpenLoopReadsOnePass() throws Exception {
    File scenarioFile = fixture("cogen_open_loop.xml");
    List<String> reads = run(scenarioFile, true, Collections.singletonList("SELECT"), "-q");
    List<String> expected = onePass(scenarioFile);
    Collections.sort(reads);
    Collections.sort(expected);
    assertEquals(expected, reads);
  }
}
