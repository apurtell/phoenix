/**
 * Verifies the co-generation invariants and the predicate forms that the co-generation decoder can
 * bind, as specified by RQ-195 and RQ-196. Each defect is introduced through a single edit to a
 * clean fixture and produces exactly one finding.
 */
public class CoGenerationRulesTest {
  private static final String COGEN = "<coGeneration seed=\"7\" blockSize=\"50\"/>";
  private static final String LOOKUP_PREFIX = "SELECT V FROM PHERF.VALIDATION_CLEAN ";
  private static final String LOOKUP = LOOKUP_PREFIX + "WHERE K1 = [K1] AND K2 = [K2]\"/>";
  private static final String SCAN =
    "SELECT K2, V FROM PHERF.VALIDATION_CLEAN WHERE K1 &gt;= [K1] AND K1 &lt;= [K1]";
  private static final String DESC_SCAN =
    "SELECT K2, V FROM PHERF.VALIDATION_DESC WHERE K1 &gt;= [K1] AND K1 &lt;= [K1]";
  private static final String SCENARIOS_END = "    </scenarios>";
  private static final List<String> COGEN_RULES = Arrays.asList("cogen.settings", "cogen.walk",
    "cogen.writer-blocks", "cogen.offsets", "cogen.watermark", "cogen.range", "key.coverage",
    "predicate.in-list", "predicate.row-value", "predicate.range-bounds");

  @Rule
  public final TemporaryFolder folder = new TemporaryFolder();

  /**
   * A walk step that shares a common factor with the window size revisits indexes before covering
   * the entire window. Because no configuration setting specifies the step directly and the walk
   * always selects a coprime step, no scenario can fail this validation check; therefore, this test
   * invokes the check directly and verifies that the steps generated by the walk pass it.
   */
  @Test
  public void testNonCoprimeWalkStep() throws Exception {
    ValidationReport report = new ValidationReport();
    ScenarioValidator.checkWalk(report, "f.xml", "scenario s querySet 1", 12, 8);
    assertEquals(Collections.singletonList("cogen.walk"), rules(report));
    String message = report.getFindings().get(0).getMessage();
    assertTrue(message, message.contains("step 8") && message.contains("12"));

    report = new ValidationReport();
    ScenarioValidator.checkWalk(report, "f.xml", "scenario s querySet 1", 12, 5);
    assertEquals(0, report.getErrors());
    // The walk algorithm ensures that every step generated in production is coprime to the window.
    for (long window = 1; window <= 300; window++) {
      ScenarioValidator.checkWalk(report, "f.xml", "w", window, Walk.step(42, window));
    }
    assertEquals(0, report.getErrors());
  }

  /**
   * Verifies that a dataset of 3 rows leaves worker 3 of 4 in the closed loop without any committed
   * rows at the start of execution.
   */
  @Test
  public void testEmptyReaderShare() throws Exception {
    ValidationReport report = validate(
      variant(folder.getRoot(), CLEAN, edit(CLEAN, "rowCount=\"1000\"", "rowCount=\"3\"")));
    assertEquals(Collections.singletonList("cogen.walk"), rules(report));
    Finding finding = report.getFindings().get(0);
    assertEquals("scenario validationClean querySet 2", finding.getWhere());
    assertTrue(finding.getMessage(), finding.getMessage().contains("worker 3 of 4"));
  }

  /**
   * Setting a cluster limit below the block size on a table with a one-column key causes a block to
   * generate equal keys.
   */
  @Test
  public void testOverlappingWriterBlocks() throws Exception {
    ValidationReport report = validate(variant(folder.newFolder("one"), CLEAN,
      edit(CLEAN, "PRIMARY KEY (K1, K2)", "PRIMARY KEY (K1)"),
      edit(CLEAN, COGEN, "<coGeneration seed=\"7\" blockSize=\"50\" clusterLimit=\"10\"/>")));
    assertEquals(Collections.singletonList("cogen.writer-blocks"), rules(report));
    assertTrue(report.getFindings().get(0).getMessage(),
      report.getFindings().get(0).getMessage().contains("overwrite each other"));

    // A cluster limit equal to the block size does not cluster keys within the block.
    report = validate(variant(folder.newFolder("equal"), CLEAN,
      edit(CLEAN, "PRIMARY KEY (K1, K2)", "PRIMARY KEY (K1)"),
      edit(CLEAN, COGEN, "<coGeneration seed=\"7\" blockSize=\"50\" clusterLimit=\"50\"/>")));
    assertEquals(new ArrayList<String>(), rules(report));
  }

  /**
   * Two co-generated scenarios within a single run that write to the same table must define
   * disjoint offset ranges.
   */
  @Test
  public void testOverlappingProcessOffsets() throws Exception {
    ValidationReport report =
      validate(variant(folder.newFolder("overlap"), CLEAN, second("validationCleanB", "500")));
    assertEquals(Collections.singletonList("cogen.offsets"), rules(report));
    String message = report.getFindings().get(0).getMessage();
    assertTrue(message, message.contains("[0, 1000)") && message.contains("[500, 1500)"));

    // Offset ranges that meet at the exact boundary remain disjoint and valid.
    report =
      validate(variant(folder.newFolder("boundary"), CLEAN, second("validationCleanB", "1000")));
    assertEquals(new ArrayList<String>(), rules(report));

    // Because writeParams writers append rows beyond the configured row count, the resulting offset
    // range has no upper bound.
    report = validate(variant(folder.newFolder("open"), CLEAN,
      edit(CLEAN, COGEN, COGEN + "<writeParams executionDurationInMs=\"100\"/>"),
      second("validationCleanB", "1000")));
    assertEquals(Collections.singletonList("cogen.offsets"), rules(report));

    // An offset range whose upper bound cannot fit within a long value causes an arithmetic
    // overflow.
    report = validate(variant(folder.newFolder("overflow"), CLEAN,
      second("validationCleanB", "9223372036854775000")));
    assertEquals(Collections.singletonList("cogen.offsets"), rules(report));
    assertTrue(report.getFindings().get(0).getMessage(),
      report.getFindings().get(0).getMessage().contains("overflows"));
  }

  /**
   * A second scenario that reuses the same scenario name shares the underlying row cursor, causing
   * its load phase to reset the watermark.
   */
  @Test
  public void testNonMonotonicWatermarkSetting() throws Exception {
    ValidationReport report = validate(variant(folder.getRoot(), CLEAN,
      edit(CLEAN, SCENARIOS_END,
        "        <scenario tableName=\"PHERF.VALIDATION_OTHER\" rowCount=\"10\""
          + " name=\"validationClean\">" + COGEN + "</scenario>\n" + SCENARIOS_END)));
    assertEquals(Collections.singletonList("cogen.watermark"), rules(report));
    assertTrue(report.getFindings().get(0).getMessage(),
      report.getFindings().get(0).getMessage().contains("not unique"));
  }

  @Test
  public void testValidCoGeneratedFixturePasses() throws Exception {
    String path = ValidationFixtures.file(CLEAN);
    ValidationReport report = validate(path);
    assertEquals(report.getFindings().toString(), 0, report.getErrors());
    assertEquals(Arrays.asList(path, ValidationFixtures.file(CLEAN_PROFILE)), report.getFiles());
    report = validate(ValidationFixtures.file(CLEAN_DESC));
    assertEquals(report.getFindings().toString(), 0, report.getErrors());
  }

  /**
   * When the coGeneration element is omitted, the validator does not evaluate any co-generation
   * rules against these same defects.
   */
  @Test
  public void testRulesDoNotRunWithoutCoGeneration() throws Exception {
    String clustered = "<coGeneration seed=\"7\" blockSize=\"50\" clusterLimit=\"10\"/>";
    String offset = "<coGeneration seed=\"7\" blockSize=\"50\" offset=\"500\"/>";
    Edit off = edit(CLEAN, COGEN, "");
    // Each test case pairs the edits that introduce a defect with the edits that strip every
    // coGeneration element from the fixture.
    List<Edit[][]> cases = new ArrayList<>();
    cases.add(new Edit[][] { { edit(CLEAN, "rowCount=\"1000\"", "rowCount=\"3\"") }, { off } });
    cases.add(new Edit[][] {
      { edit(CLEAN, "PRIMARY KEY (K1, K2)", "PRIMARY KEY (K1)"), edit(CLEAN, COGEN, clustered) },
      { edit(CLEAN, clustered, "") } });
    cases.add(
      new Edit[][] { { second("validationCleanB", "500") }, { off, edit(CLEAN, offset, "") } });
    cases.add(new Edit[][] {
      { edit(CLEAN, LOOKUP, LOOKUP_PREFIX + "WHERE K1 = [K1] AND K2 = [K1]\"/>") }, { off } });
    cases.add(new Edit[][] {
      { edit(CLEAN, LOOKUP, LOOKUP_PREFIX + "WHERE K1 IN ([K1], [K1]) AND K2 = [K2]\"/>") },
      { off } });
    cases.add(new Edit[][] {
      { edit(CLEAN, LOOKUP, LOOKUP_PREFIX + "WHERE K1 = [K1] AND K2 IN ([K2], K1)\"/>") },
      { off } });
    cases.add(new Edit[][] { { edit(CLEAN, SCAN, SCAN + " AND K2 IN ([K2])") }, { off } });
    cases.add(new Edit[][] { { edit(CLEAN, SCAN, "SELECT K2, V FROM PHERF.VALIDATION_CLEAN WHERE"
      + " (K1, K2) &gt;= ([K1], [K2]) AND K1 &lt;= [K1]") }, { off } });
    cases.add(new Edit[][] {
      { edit(CLEAN, SCAN,
        "SELECT K2, V FROM PHERF.VALIDATION_CLEAN WHERE K1 &lt;= [K1] AND K1 &gt;= [K1]") },
      { off } });
    for (int i = 0; i < cases.size(); i++) {
      Edit[] defect = cases.get(i)[0];
      ValidationReport on = validate(variant(folder.newFolder("on" + i), CLEAN, defect));
      assertTrue("Case " + i + " gives no co-generation finding: " + on.getFindings(),
        hasCoGenerationRule(on));
      List<Edit> edits = new ArrayList<>(Arrays.asList(defect));
      edits.addAll(Arrays.asList(cases.get(i)[1]));
      ValidationReport report =
        validate(variant(folder.newFolder("off" + i), CLEAN, edits.toArray(new Edit[0])));
      assertTrue("Case " + i + ": " + report.getFindings(), !hasCoGenerationRule(report));
    }
  }

  /** Validates the supported and unsupported IN list predicate forms required by RQ-196. */
  @Test
  public void testInListForms() throws Exception {
    // Two elements within a single list refer to the same row because a single statement binds only
    // one row.
    assertOne("predicate.in-list", "one row", CLEAN,
      edit(CLEAN, LOOKUP, LOOKUP_PREFIX + "WHERE K1 IN ([K1], [K1]) AND K2 = [K2]\"/>"));
    // A range statement brackets a single block using the leading key alone.
    assertOne("predicate.in-list", "SCAN", CLEAN, edit(CLEAN, SCAN, SCAN + " AND K2 IN ([K2])"));
    // Phoenix requires every element in an IN list to be a constant expression.
    assertOne("predicate.in-list", "constant", CLEAN,
      edit(CLEAN, LOOKUP, LOOKUP_PREFIX + "WHERE K1 = [K1] AND K2 IN ([K2], K1)\"/>"));
    // Supported forms include a list containing one ruled element and a list of literal values.
    assertNone(CLEAN, edit(CLEAN, LOOKUP, LOOKUP_PREFIX + "WHERE K1 IN ([K1]) AND K2 = [K2]\"/>"),
      edit(CLEAN, SCAN, SCAN + " AND K2 IN (1, 2, 3)"));
  }

  /** Validates the row value constructor predicate forms governed by RQ-196. */
  @Test
  public void testRowValueConstructorForms() throws Exception {
    assertOne("predicate.row-value", "leading key", CLEAN,
      edit(CLEAN, SCAN,
        "SELECT K2, V FROM PHERF.VALIDATION_CLEAN WHERE (K1, K2) &gt;= ([K1], [K2]) AND K1 &lt;="
          + " [K1]"));
    assertOne("predicate.row-value", "NULL", CLEAN,
      edit(CLEAN, LOOKUP, LOOKUP_PREFIX + "WHERE (K1, K2) = ([K1], [K2], [K2])\"/>"));
    assertOne("predicate.row-value", "arity", CLEAN,
      edit(CLEAN, SCAN, SCAN + " AND (K2, V) IN ((1, 'a'), (2, 'b', 'c'))"));
    // Supported forms include a point equality across the full primary key and an inequality with
    // unequal arity, which compares the common prefix.
    assertNone(CLEAN, edit(CLEAN, LOOKUP, LOOKUP_PREFIX + "WHERE (K1, K2) = ([K1], [K2])\"/>"),
      edit(CLEAN, SCAN, SCAN + " AND (K2, V) &gt;= (5)"));
    assertNone(CLEAN,
      edit(CLEAN, LOOKUP,
        LOOKUP_PREFIX + "WHERE K1 = [K1] AND K2 = [K2] AND (K1, K2, V) &gt;= (0, 0)\"/>"),
      edit(CLEAN, SCAN, SCAN + " AND (K2, V) &lt; (5, 'a', 1)"));
  }

  /**
   * Validates range predicates on a descending leading key under RQ-196, where the bounds compare
   * column values rather than the storage key order.
   */
  @Test
  public void testDescendingKeyForms() throws Exception {
    assertOne("predicate.range-bounds", "DESC", CLEAN_DESC, edit(CLEAN_DESC, DESC_SCAN,
      "SELECT K2, V FROM PHERF.VALIDATION_DESC WHERE K1 &lt;= [K1] AND K1 &gt;= [K1]"));
    assertOne("predicate.range-bounds", "strict", CLEAN_DESC, edit(CLEAN_DESC, DESC_SCAN,
      "SELECT K2, V FROM PHERF.VALIDATION_DESC WHERE K1 &gt; [K1] AND K1 &lt;= [K1]"));
    assertOne("predicate.range-bounds", "top level", CLEAN_DESC, edit(CLEAN_DESC, DESC_SCAN,
      "SELECT K2, V FROM PHERF.VALIDATION_DESC WHERE (K1 &gt;= [K1] OR K1 &lt;= [K1])"));
    // Supported range forms include >= followed by <=, BETWEEN, and their mirrored equivalents for
    // both SCAN and DELETE statements.
    assertNone(CLEAN_DESC);
  }

  /**
   * Verifies the requirement carried from P7 that coGeneration attributes are parsed as text and
   * that an invalid value explicitly names the offending attribute.
   */
  @Test
  public void testCoGenerationAttributeText() throws Exception {
    assertOne("cogen.settings", "seed is not a valid value: 'x7'", CLEAN,
      edit(CLEAN, "seed=\"7\"", "seed=\"x7\""));
    assertOne("cogen.settings", "blockSize is less than 1", CLEAN,
      edit(CLEAN, "blockSize=\"50\"", "blockSize=\"0\""));
  }

  /**
   * Verifies the requirement carried from P7 that a -q run executed without a preceding load phase
   * initializes the watermark at the configured row count, requiring every reader share and scan
   * window share to be non-empty at that count.
   */
  @Test
  public void testReadersAtRowCount() throws Exception {
    assertOne("cogen.walk", "worker 3 of 4", CLEAN,
      edit(CLEAN, "rowCount=\"1000\"", "rowCount=\"3\""));

    ValidationReport report = validate(
      variant(folder.newFolder("zero"), CLEAN, edit(CLEAN, "rowCount=\"1000\"", "rowCount=\"0\"")));
    assertEquals(Arrays.asList("cogen.walk", "cogen.walk", "cogen.walk", "cogen.walk"),
      rules(report));
    List<String> where = new ArrayList<>();
    for (Finding finding : report.getFindings()) {
      where.add(finding.getWhere() + ": " + finding.getMessage().split(":")[0]);
    }
    assertEquals(Arrays.asList("scenario validationClean querySet 1: SELECT",
      "scenario validationClean querySet 1: SCAN", "scenario validationClean querySet 1: DELETE",
      "scenario validationClean querySet 2: SELECT"), where);

    // Partitioning 100 rows into blocks of 50 produces only 2 windows, so running scans at a
    // concurrency of 4 leaves 2 workers without a window.
    assertOne("cogen.walk", "SCAN", CLEAN, edit(CLEAN, "rowCount=\"1000\"", "rowCount=\"100\""),
      edit(CLEAN, "numberOfExecutions=\"10\">",
        "numberOfExecutions=\"10\">\n" + "<query id=\"closedScan\" kind=\"SCAN\" statement=\""
          + SCAN.replace("K2, V", "V") + "\"/>"));

    // Providing at least one row for each concurrent worker satisfies the partitioning requirement.
    assertNone(CLEAN, edit(CLEAN, "rowCount=\"1000\"", "rowCount=\"4\""));
  }

  /**
   * Constructs an edit that appends a second co-generated scenario targeting the same table at the
   * specified row offset.
   */
  private static Edit second(String name, String offset) {
    return edit(CLEAN, SCENARIOS_END,
      "        <scenario tableName=\"PHERF.VALIDATION_CLEAN\" rowCount=\"1000\" name=\"" + name
        + "\"><coGeneration seed=\"7\" blockSize=\"50\" offset=\"" + offset + "\"/></scenario>\n"
        + SCENARIOS_END);
  }

  private void assertOne(String rule, String text, String fixture, Edit... edits) throws Exception {
    ValidationReport report = validate(variant(folder.newFolder(), fixture, edits));
    assertEquals(Collections.singletonList(rule), rules(report));
    String message = report.getFindings().get(0).getMessage();
    assertTrue(message, message.contains(text));
  }

  private void assertNone(String fixture, Edit... edits) throws Exception {
    ValidationReport report = validate(variant(folder.newFolder(), fixture, edits));
    assertEquals(new ArrayList<String>(), rules(report));
  }

  private static boolean hasCoGenerationRule(ValidationReport report) {
    for (String rule : rules(report)) {
      if (COGEN_RULES.contains(rule)) {
        return true;
      }
    }
    return false;
  }
}
