package org.apache.phoenix.pherf.latency;

import com.google.gson.GsonBuilder;
import java.io.BufferedOutputStream;
import java.io.File;
import java.io.FileOutputStream;
import java.io.IOException;
import java.io.PrintStream;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.StandardCopyOption;
import java.util.ArrayList;
import java.util.List;
import org.HdrHistogram.Histogram;
import org.HdrHistogram.HistogramLogWriter;

/**
 * Defines the serialization formats for latency output files. The authoritative specification for
 * these formats resides in phoenix-pherf/LATENCY.md, as they are consumed by the execution harness,
 * offline analysis utilities, and the distributed controller.
 * <ul>
 * <li>LATENCY&lt;suffix&gt;.json: stores the structured JSON summary report using format
 * {@link #FORMAT} and schema version {@link #VERSION}.</li>
 * <li>LATENCY&lt;suffix&gt;.hlog: records a single cumulative histogram for each tracked key
 * spanning the entire run.</li>
 * <li>LATENCY&lt;suffix&gt;_intervals.hlog: captures time-series interval histograms whenever
 * interval export is enabled.</li>
 * </ul>
 * Every histogram entry within a log file is labeled with a composite tag generated by
 * {@link #tag(String, String)}.
 */
public final class LatencyReport {
  public static final String FORMAT = "pherf-latency";
  /** This version increments only for a format change that existing readers cannot parse. */
  public static final int VERSION = 1;
  private static final String PREFIX = "LATENCY";
  private static final String COMMENT = "[Pherf latency log " + VERSION + ": microseconds, lowest "
    + LatencyRecorders.LOWEST_US + ", highest " + LatencyRecorders.HIGHEST_US + ", "
    + LatencyRecorders.DIGITS + " significant digits, Tag=OPERATION|PHASE]";
  private static final char SEPARATOR = '|';
  // The histogram log reader tokenizes input on spaces, commas, carriage returns (CR), and line
  // feeds (LF), while '%' introduces a percent-encoded escape sequence.
  private static final String ESCAPED = "% ,\r\n";

  private LatencyReport() {
  }

  static String jsonName(String label) {
    return PREFIX + "_" + label + ".json";
  }

  static String hlogName(String label) {
    return PREFIX + "_" + label + ".hlog";
  }

  static String intervalsName(String label) {
    return PREFIX + "_" + label + "_intervals.hlog";
  }

  /**
   * Formats the log tag for a key by joining the escaped operation name, the '|' delimiter, and the
   * phase.
   */
  public static String tag(String operation, String phase) {
    StringBuilder tag = new StringBuilder();
    for (char c : operation.toCharArray()) {
      if (ESCAPED.indexOf(c) >= 0) {
        tag.append(String.format("%%%02X", (int) c));
      } else {
        tag.append(c);
      }
    }
    return tag.append(SEPARATOR).append(phase).toString();
  }

  /** Extracts and decodes the operation name and phase from a composite log tag. */
  public static String[] parseTag(String tag) {
    int split = tag.lastIndexOf(SEPARATOR);
    if (split < 0) {
      throw new IllegalArgumentException("Not a latency tag: " + tag);
    }
    StringBuilder operation = new StringBuilder();
    for (int i = 0; i < split; i++) {
      char c = tag.charAt(i);
      if (c == '%' && i + 2 < split) {
        operation.append((char) Integer.parseInt(tag.substring(i + 1, i + 3), 16));
        i += 2;
      } else {
        operation.append(c);
      }
    }
    return new String[] { operation.toString(), tag.substring(split + 1) };
  }

  /**
   * Writes the JSON summary report and the cumulative run histogram log from the provided total
   * histograms, which are already populated with their tags.
   */
  static void write(File dir, String label, long startMs, long endMs, boolean intervals,
    List<Histogram> totals) throws IOException {
    Log log = new Log(new File(dir, hlogName(label)), startMs);
    try {
      for (Histogram total : totals) {
        log.write(startMs, endMs, total);
      }
    } finally {
      log.close();
    }
    Report report = new Report();
    report.label = label;
    report.startMs = startMs;
    report.endMs = endMs;
    report.hlog = hlogName(label);
    report.intervals = intervals ? intervalsName(label) : null;
    for (Histogram total : totals) {
      report.histograms.add(new Summary(total));
    }
    // The JSON report is materialized last so that any consumer observing it is guaranteed to find
    // a completed histogram log. Performing an atomic move ensures that readers never encounter a
    // partially written report file.
    String json =
      new GsonBuilder().setPrettyPrinting().disableHtmlEscaping().create().toJson(report) + "\n";
    Path target = new File(dir, jsonName(label)).toPath();
    Path temporary = new File(dir, jsonName(label) + ".tmp").toPath();
    Files.write(temporary, json.getBytes(StandardCharsets.UTF_8));
    Files.move(temporary, target, StandardCopyOption.ATOMIC_MOVE,
      StandardCopyOption.REPLACE_EXISTING);
  }

  /** Encapsulates a histogram log file recorded in microseconds with the standard Pherf header. */
  static final class Log {
    private final File file;
    private final PrintStream out;
    private final HistogramLogWriter writer;
    private final long baseMs;

    Log(File file, long baseMs) throws IOException {
      this.file = file;
      this.baseMs = baseMs;
      // Each line is flushed immediately to the file so that consumers can tail the log while the
      // benchmark run is in progress.
      this.out = new PrintStream(new BufferedOutputStream(new FileOutputStream(file)), true,
        StandardCharsets.UTF_8.name());
      this.writer = new HistogramLogWriter(out);
      writer.outputComment(COMMENT);
      writer.outputLogFormatVersion();
      writer.outputStartTime(baseMs);
      writer.outputBaseTime(baseMs);
      writer.outputLegend();
      check();
    }

    /** Writes a single histogram entry covering the time window [startMs, endMs]. */
    void write(long startMs, long endMs, Histogram histogram) throws IOException {
      histogram.setStartTimeStamp(startMs);
      histogram.setEndTimeStamp(endMs);
      writer.outputIntervalHistogram((startMs - baseMs) / 1000.0, (endMs - baseMs) / 1000.0,
        histogram, 1.0);
      check();
    }

    void close() throws IOException {
      writer.close();
      check();
    }

    private void check() throws IOException {
      if (out.checkError()) {
        throw new IOException("Cannot write " + file);
      }
    }
  }

  // Defines the schema for version 1 of the JSON report. Gson serializes these fields in their
  // declared order and omits any field with a null value.
  @SuppressWarnings("unused")
  private static final class Report {
    private final String format = FORMAT;
    private final int version = VERSION;
    private String label;
    private long startMs;
    private long endMs;
    private final RecorderConfig recorder = new RecorderConfig();
    private String hlog;
    private String intervals;
    private final List<Summary> histograms = new ArrayList<>();
  }

  @SuppressWarnings("unused")
  private static final class RecorderConfig {
    private final long lowestUs = LatencyRecorders.LOWEST_US;
    private final long highestUs = LatencyRecorders.HIGHEST_US;
    private final int significantDigits = LatencyRecorders.DIGITS;
  }

  @SuppressWarnings("unused")
  private static final class Summary {
    private final String operation;
    private final String phase;
    private final long count;
    private final long minUs;
    private final long maxUs;
    private final double meanUs;
    private final long p50Us;
    private final long p90Us;
    private final long p99Us;
    private final long p999Us;

    Summary(Histogram histogram) {
      String[] key = parseTag(histogram.getTag());
      operation = key[0];
      phase = key[1];
      count = histogram.getTotalCount();
      minUs = histogram.getMinValue();
      maxUs = histogram.getMaxValue();
      meanUs = histogram.getMean();
      p50Us = histogram.getValueAtPercentile(50);
      p90Us = histogram.getValueAtPercentile(90);
      p99Us = histogram.getValueAtPercentile(99);
      p999Us = histogram.getValueAtPercentile(99.9);
    }
  }
}
