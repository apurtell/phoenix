package org.apache.phoenix.pherf.exception;

/**
 * Signals that a validation rule has failed. When this exception is raised, Pherf terminates with
 * the dedicated validation exit code, distinguishing validation failures from the exit code used
 * for all other errors.
 */
public class ValidationException extends Exception {
  public ValidationException(String message) {
    super(message);
  }
}
