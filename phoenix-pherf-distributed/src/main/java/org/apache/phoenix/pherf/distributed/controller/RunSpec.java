/**
 * Defines a distributed run specification comprising a seed, a run class, run-level properties, and
 * an ordered sequence of steps that execute sequentially. The seed is used to derive the data-plane
 * identity for each execution slot, while the run class (validation or measurement) and the verdict
 * settings derived from the run-level properties determine the fleet verdict.
 * <p>
 * {@link #parse} parses the JSON execution plan and performs all static validation checks that do
 * not require an active agent, ensuring that no agent receives an assignment for an invalid or
 * unexecutable plan. Every reported validation error identifies the exact JSON path of the
 * offending element.
 */
public final class RunSpec {
  /**
   * Defines the substitution token representing the row offset assigned to a slot. Any step that
   * references this token must specify a row count.
   */
  static final String OFFSET_TOKEN = "${pherf.slot.offset}";
  /**
   * Specifies the byte margin reserved within a message body to accommodate the trace metadata and
   * protocol envelope of an assignment message.
   */
  static final int ASSIGN_MARGIN = 1024;
  /**
   * Provides a synthetic run identifier matching the maximum length generated by the controller,
   * used to evaluate worst-case payload size limits for assignment messages.
   */
  private static final String LONGEST_RUN_ID = "00000000T000000000Z-" + Long.MAX_VALUE;
  private static final String NOT_JSON = "the plan is not valid JSON: ";
  /** Sentinel object representing a JSON null value within the parsed syntax tree. */
  private static final Object JSON_NULL = new Object();
  private static final String NAME_RULE =
    "not a document name; a name matches" + " [A-Za-z0-9._-]{1,128} and does not start with '.'";
  private static final Set<String> PLAN_KEYS =
    new HashSet<>(Arrays.asList("seed", "runClass", "properties", "steps"));
  private static final Set<String> STEP_KEYS = new HashSet<>(Arrays.asList("agents", "weights",
    "scenario", "documents", "args", "rate", "durationMs", "threads", "rows", "properties"));
  /**
   * Maps each recognized spelling of a Pherf command-line option managed directly by the agent to
   * its canonical option name for error reporting and a usage hint.
   */
  private static final Map<String, String[]> AGENT_OPTIONS = new LinkedHashMap<>();
  /**
   * Identifies Pherf execution modes that bypass the validation gate or rely on the query server.
   */
  private static final Map<String, String> REFUSED_MODES = new LinkedHashMap<>();

  static {
    agentOption("use the step field scenario", "scenarioFile");
    agentOption("the agent sets it", "label");
    agentOption("the agent takes it from PHERF_ZOOKEEPER", "z", "zookeeper");
    agentOption("use the step field durationMs", "runDurationMs");
    agentOption("use the step field threads", "threadCount");
    agentOption("use the step field rate", "targetRate");
    agentOption("use the step field rows", "rowCountOverride");
    agentOption("the agent runs it before each step", "validate");
    for (String[] mode : new String[][] { { "analyze" }, { "compare" }, { "listFiles" },
      { "h", "help" }, { "t", "thin" }, { "s", "server" } }) {
      for (String spelling : mode) {
        REFUSED_MODES.put(spelling, "-" + mode[0]);
      }
    }
  }

  private static void agentOption(String hint, String name, String... other) {
    AGENT_OPTIONS.put(name, new String[] { "-" + name, hint });
    for (String spelling : other) {
      AGENT_OPTIONS.put(spelling, new String[] { "-" + name, hint });
    }
  }

  private final long seed;
  private final String runClass;
  private final Map<String, String> properties;
  private final VerdictSettings verdictSettings;
  private final List<StepSpec> steps;
  /** Stores the partitioned workload slices calculated for the execution slots of each step. */
  private final List<List<Split.Slice>> slices = new ArrayList<>();

  private RunSpec(long seed, String runClass, Map<String, String> properties,
    VerdictSettings verdictSettings, List<StepSpec> steps) {
    this.seed = seed;
    this.runClass = runClass;
    this.properties = new LinkedHashMap<>(properties);
    this.verdictSettings = verdictSettings;
    this.steps = new ArrayList<>(steps);
    for (StepSpec step : steps) {
      slices.add(Split.slices(step));
    }
  }

  public long getSeed() {
    return seed;
  }

  /** Returns the run class of this specification, which is either validation or measurement. */
  public String getRunClass() {
    return runClass;
  }

  /**
   * Returns the verdict settings derived from the run-level properties. Step-level properties do
   * not alter these settings.
   */
  public VerdictSettings getVerdictSettings() {
    return verdictSettings;
  }

  /**
   * Returns the run-level properties, which take precedence over any step-level property
   * definitions.
   */
  public Map<String, String> getProperties() {
    return Collections.unmodifiableMap(properties);
  }

  public List<StepSpec> getSteps() {
    return Collections.unmodifiableList(steps);
  }

  /**
   * Resolves the effective property map for the execution slots of a step by overlaying the
   * run-level properties on top of the step-level properties.
   */
  Map<String, String> properties(StepSpec step) {
    Map<String, String> merged = new LinkedHashMap<>(step.getProperties());
    merged.putAll(properties);
    return merged;
  }

  /**
   * Constructs the execution assignment for a specific slot within a step. To ensure that every
   * workload slice in the entire run is validated prior to execution, slot s of step 0 is also
   * assigned all slots k from each subsequent step where k mod n = s, with n representing the total
   * agent count of step 0.
   */
  Assignment assignment(String runId, int index, int slot) {
    StepSpec step = steps.get(index);
    Split.Slice slice = slices.get(index).get(slot);
    List<Assignment> validations = new ArrayList<>();
    if (index == 0) {
      for (int later = 1; later < steps.size(); later++) {
        for (int k = slot; k < steps.get(later).getAgents(); k += step.getAgents()) {
          validations.add(assignment(runId, later, k));
        }
      }
    }
    return new Assignment(runId, index, DataPlaneIdentity.derive(seed, slot, slice.getOffset()),
      step.getScenario(), step.getDocuments(), step.getArgs(), slice.getShare(), properties(step),
      validations);
  }

  /**
   * Parses and validates a JSON run plan specification.
   * @throws IllegalArgumentException identifying the JSON path of the first validation error
   *                                  encountered
   */
  public static RunSpec parse(String json) {
    Object tree = read(json);
    if (!(tree instanceof JsonMap)) {
      throw new IllegalArgumentException("the plan is not a JSON object");
    }
    JsonMap plan = (JsonMap) tree;
    keys(plan, "", PLAN_KEYS);
    long seed = integer(plan, "", "seed");
    Map<String, String> properties = strings(plan, "", "properties", false);
    agentProperties(properties, "properties");
    Properties verdict = new Properties();
    verdict.putAll(properties);
    VerdictSettings verdictSettings;
    try {
      verdictSettings = VerdictSettings.of(verdict);
    } catch (IllegalArgumentException e) {
      throw error("properties", e.getMessage());
    }
    if (!plan.containsKey("steps")) {
      throw error("steps", "required");
    }
    List<Object> elements = array(plan.get("steps"), "steps");
    if (elements.isEmpty()) {
      throw error("steps", "no step; a plan needs at least one");
    }
    List<StepSpec> steps = new ArrayList<>();
    for (int i = 0; i < elements.size(); i++) {
      steps.add(step(elements.get(i), "steps[" + i + "]"));
    }
    if (!plan.containsKey("runClass")) {
      throw error("runClass", "required");
    }
    String runClass = string(plan.get("runClass"), "runClass");
    if (!Replicate.VALIDATION.equals(runClass) && !Replicate.MEASUREMENT.equals(runClass)) {
      throw error("runClass",
        runClass + " is not " + Replicate.VALIDATION + " or " + Replicate.MEASUREMENT);
    }
    RunSpec spec = new RunSpec(seed, runClass, properties, verdictSettings, steps);
    for (int i = 0; i < steps.size(); i++) {
      spec.checkSlots(i, "steps[" + i + "]");
    }
    return spec;
  }

  private static StepSpec step(Object value, String path) {
    JsonMap step = object(value, path);
    keys(step, path, STEP_KEYS);
    long agents = integer(step, path, "agents");
    if (agents < 1 || agents > DataPlaneIdentity.MAX_SLOTS) {
      throw error(child(path, "agents"),
        agents + " is outside 1 to " + DataPlaneIdentity.MAX_SLOTS);
    }
    long[] weights = new long[(int) agents];
    Arrays.fill(weights, 1);
    if (step.containsKey("weights")) {
      String at = child(path, "weights");
      List<Object> given = array(step.get("weights"), at);
      long[] parsed = new long[given.size()];
      for (int i = 0; i < parsed.length; i++) {
        parsed[i] = integer(given.get(i), at + "[" + i + "]");
      }
      if (parsed.length != agents) {
        throw error(at, parsed.length + " weights for " + agents + " agents");
      }
      for (int i = 0; i < parsed.length; i++) {
        atLeastOne(parsed[i], at + "[" + i + "]");
      }
      weights = parsed;
    }
    if (!step.containsKey("scenario")) {
      throw error(child(path, "scenario"), "required");
    }
    String scenario = string(step.get("scenario"), child(path, "scenario"));
    String at = child(path, "documents");
    Map<String, String> documents = strings(step, path, "documents", true);
    for (String name : documents.keySet()) {
      if (!Assignment.DOCUMENT_NAME.matcher(name).matches()) {
        throw error(entry(at, name), NAME_RULE);
      }
    }
    if (!documents.containsKey(scenario)) {
      throw error(at, "no document named " + scenario + " for the scenario");
    }
    List<String> args = new ArrayList<>();
    if (step.containsKey("args")) {
      List<Object> given = array(step.get("args"), child(path, "args"));
      for (int i = 0; i < given.size(); i++) {
        String arg = string(given.get(i), child(path, "args") + "[" + i + "]");
        checkArg(arg, child(path, "args") + "[" + i + "]");
        args.add(arg);
      }
    }
    Long rate = positive(step, path, "rate");
    Long durationMs = positive(step, path, "durationMs");
    Long threads = positive(step, path, "threads");
    Long rows = positive(step, path, "rows");
    Map<String, String> properties = strings(step, path, "properties", false);
    agentProperties(properties, child(path, "properties"));
    return new StepSpec(weights, scenario, documents, args, rate, durationMs, threads, rows,
      properties);
  }

  /**
   * Performs step validation checks that depend on the partitioned workload slices, verifying that
   * every slot receives a runnable share and that its serialized assignment fits within the
   * protocol size limit.
   */
  private void checkSlots(int index, String path) {
    StepSpec step = steps.get(index);
    Map<String, String> merged = properties(step);
    if (step.getRows() == null && usesOffset(step, merged)) {
      throw error(path, OFFSET_TOKEN + " needs rows");
    }
    List<Split.Slice> slices = this.slices.get(index);
    String[] names = { "rate", "threads", "rows" };
    Long[] totals = { step.getRate(), step.getThreads(), step.getRows() };
    for (int slot = 0; slot < slices.size(); slot++) {
      Share share = slices.get(slot).getShare();
      Long[] shares = { share.getRate(), share.getThreads(), share.getRows() };
      for (int q = 0; q < names.length; q++) {
        // A calculated share of 0 would be interpreted as omitting the override, causing the slot
        // to fall back to the unpartitioned value configured in its scenario document.
        if (shares[q] != null && shares[q] == 0) {
          throw error(child(path, names[q]), "slot " + slot + " gets a share of 0 of " + totals[q]);
        }
      }
      if (share.getRows() != null && share.getRows() > Integer.MAX_VALUE) {
        throw error(child(path, "rows"), "slot " + slot + " gets " + share.getRows()
          + " rows; -rowCountOverride takes at most " + Integer.MAX_VALUE);
      }
    }
    // Because an agent rejects any response exceeding the protocol body size limit, an oversized
    // payload would cause the run to remain stalled in the ASSIGNED state indefinitely. Every
    // slice in the assignment embeds the run identifier, and in step 0, slot 0 accumulates the
    // largest number of validation slices from subsequent steps.
    long bytes = Codec.encode(new Assign(assignment(LONGEST_RUN_ID, index, 0)))
      .getBytes(StandardCharsets.UTF_8).length;
    long limit = Protocol.MAX_BODY_BYTES - ASSIGN_MARGIN;
    if (bytes > limit) {
      throw error(path, "the assign of slot 0 has " + bytes + " bytes; the limit is " + limit);
    }
  }

  private static boolean usesOffset(StepSpec step, Map<String, String> properties) {
    for (Map<String, String> values : Arrays.asList(step.getDocuments(), properties)) {
      for (String value : values.values()) {
        if (value.contains(OFFSET_TOKEN)) {
          return true;
        }
      }
    }
    return false;
  }

  /**
   * Rejects command-line options reserved for agent management as well as execution modes that are
   * incompatible with distributed runs.
   */
  private static void checkArg(String arg, String path) {
    String name;
    if (arg.startsWith("--")) {
      name = arg.substring(2);
    } else if (arg.startsWith("-")) {
      name = arg.substring(1);
    } else {
      return;
    }
    int equals = name.indexOf('=');
    if (equals >= 0) {
      name = name.substring(0, equals);
    }
    String[] owned = AGENT_OPTIONS.get(name);
    if (owned != null) {
      throw error(path, owned[0] + " belongs to the agent; " + owned[1]);
    }
    String mode = REFUSED_MODES.get(name);
    if (mode != null) {
      throw error(path, mode + " is not allowed in a distributed run");
    }
  }

  private static void agentProperties(Map<String, String> properties, String path) {
    for (String key : Assignment.AGENT_PROPERTIES) {
      if (properties.containsKey(key)) {
        throw error(entry(path, key), "belongs to the agent");
      }
    }
  }

  private static IllegalArgumentException error(String path, String message) {
    return new IllegalArgumentException(path + ": " + message);
  }

  private static String child(String path, String key) {
    return path.isEmpty() ? key : path + "." + key;
  }

  private static String entry(String path, String key) {
    return path + "[\"" + key + "\"]";
  }

  private static void keys(JsonMap object, String path, Set<String> known) {
    if (object.duplicate != null) {
      throw error(child(path, object.duplicate), "duplicate key");
    }
    for (String key : object.keySet()) {
      if (!known.contains(key)) {
        throw error(child(path, key), "unknown key");
      }
    }
  }

  private static JsonMap object(Object value, String path) {
    if (!(value instanceof JsonMap)) {
      throw error(path, "not an object");
    }
    return (JsonMap) value;
  }

  @SuppressWarnings("unchecked")
  private static List<Object> array(Object value, String path) {
    if (!(value instanceof List)) {
      throw error(path, "not an array");
    }
    return (List<Object>) value;
  }

  private static String string(Object value, String path) {
    if (!(value instanceof String)) {
      throw error(path, "not a string");
    }
    return (String) value;
  }

  private static long integer(JsonMap object, String path, String key) {
    if (!object.containsKey(key)) {
      throw error(child(path, key), "required");
    }
    return integer(object.get(key), child(path, key));
  }

  private static long integer(Object value, String path) {
    if (value instanceof JsonNumber) {
      try {
        BigInteger number = new BigInteger(((JsonNumber) value).text);
        if (number.bitLength() < 64) {
          return number.longValue();
        }
      } catch (NumberFormatException e) {
        // A numeric literal containing a fractional component or an exponent is not an integer.
      }
    }
    throw error(path, "not a 64-bit integer");
  }

  private static Long positive(JsonMap object, String path, String key) {
    if (!object.containsKey(key)) {
      return null;
    }
    long value = integer(object.get(key), child(path, key));
    atLeastOne(value, child(path, key));
    return value;
  }

  private static void atLeastOne(long value, String path) {
    if (value < 1) {
      throw error(path, value + " is below 1");
    }
  }

  private static Map<String, String> strings(JsonMap object, String path, String key,
    boolean required) {
    String at = child(path, key);
    if (!object.containsKey(key)) {
      if (required) {
        throw error(at, "required");
      }
      return Collections.emptyMap();
    }
    JsonMap map = object(object.get(key), at);
    if (map.duplicate != null) {
      throw error(entry(at, map.duplicate), "duplicate key");
    }
    Map<String, String> values = new LinkedHashMap<>();
    for (Map.Entry<String, Object> value : map.entrySet()) {
      values.put(value.getKey(), string(value.getValue(), entry(at, value.getKey())));
    }
    return values;
  }

  /**
   * Represents a JSON object that preserves key insertion order and records the first duplicate key
   * encountered during parsing.
   */
  private static final class JsonMap extends LinkedHashMap<String, Object> {
    private static final long serialVersionUID = 1L;
    String duplicate;
  }

  /** Retains the raw lexical text of a JSON numeric literal as written in the input document. */
  private static final class JsonNumber {
    final String text;

    JsonNumber(String text) {
      this.text = text;
    }
  }

  /**
   * Parses strict JSON input into a tree of maps, lists, strings, numbers, booleans, and JSON_NULL.
   */
  private static Object read(String json) {
    try (JsonReader reader = new JsonReader(new StringReader(json))) {
      reader.setStrictness(Strictness.STRICT);
      Object value = value(reader);
      if (reader.peek() != JsonToken.END_DOCUMENT) {
        throw new IllegalArgumentException(NOT_JSON + "data after the plan");
      }
      return value;
    } catch (IOException e) {
      throw new IllegalArgumentException(NOT_JSON + e.getMessage(), e);
    }
  }

  private static Object value(JsonReader reader) throws IOException {
    switch (reader.peek()) {
      case BEGIN_OBJECT:
        JsonMap object = new JsonMap();
        reader.beginObject();
        while (reader.hasNext()) {
          String key = reader.nextName();
          Object value = value(reader);
          if (object.containsKey(key)) {
            if (object.duplicate == null) {
              object.duplicate = key;
            }
          } else {
            object.put(key, value);
          }
        }
        reader.endObject();
        return object;
      case BEGIN_ARRAY:
        List<Object> array = new ArrayList<>();
        reader.beginArray();
        while (reader.hasNext()) {
          array.add(value(reader));
        }
        reader.endArray();
        return array;
      case STRING:
        return reader.nextString();
      case NUMBER:
        return new JsonNumber(reader.nextString());
      case BOOLEAN:
        return reader.nextBoolean();
      case NULL:
        reader.nextNull();
        return JSON_NULL;
      default:
        throw new IOException("unexpected " + reader.peek() + " at " + reader.getPath());
    }
  }
}
