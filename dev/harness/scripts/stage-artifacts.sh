# Assembles the container image build context and builds the image through the substrate contract.
#
# The build context directory is $PX_OUT/images/<context>/, where <context> is the image tag with
# every : and / character replaced by _. The script recreates this directory from scratch on every
# invocation so that no residue from an earlier staging run remains. The context contains only the
# following entries, arranged in the layout expected by the image definition:
#   <root>        Every file and directory from the layout's image directory, along with its
#                 ignore file when one is present.
#   dist/         The release archives for HBase and Hadoop, plus the async-profiler archive when
#                 PX_DIST_ARTIFACTS lists it. Because jHiccup is distributed as a source release
#                 that build-jhiccup.sh compiles, a subsequent round stages it.
#   phoenix/      The Phoenix server, client, and Pherf JARs recorded in the build record.
# Immediately before the script copies any archive, fetch-dist.sh verifies it against its declared
# pin. The image definition unpacks the archives inside a dedicated build stage so that no archive
# reaches the final runtime image.
#
# Five staging validation checks run prior to the build, and any single failure stops the process:
#   presence    Every expected component is present in the build context, no artifact file is
#               empty, and every build argument declared by the image definition resolves to a
#               value.
#   integrity   Every copied file is byte-identical to its verified source, and every archive
#               lists its table of contents without error.
#   versions    The build record matches the selected HBase profile, and the HBase distribution
#               ships exactly one ZooKeeper JAR and one Hadoop client JAR in lib/. The script
#               extracts their release versions from the archive, passes them to the image
#               definition for secondary verification, and records them.
#   freshness   No SNAPSHOT JAR is older than a modification in the source tree.
#   strays      The build context contains no file unexplained by the sources above, and holds no
#               symbolic link, backup file, editor temporary file, or hidden file.
#
# Base images without an explicitly declared digest use a trust-on-first-use policy. The initial
# build queries sb_image_base_digest to resolve the digest for the target build architecture,
# records that digest in $PX_OUT/images/pins.env, and reuses the recorded value on every subsequent
# build. Because this pin file is runtime output, it never resides in the source working tree.
#
# Prior to running these staging checks, the script rejects any HBase release that falls outside
# the supported range of the profile's compatibility module and terminates with exit code 2.
#
# The staging record $PX_OUT/images/<context>.staged.tsv captures the complete version set of the
# context: the profile, the HBase and Hadoop releases, and the bundled ZooKeeper and Hadoop client
# versions shipped by the HBase distribution. The deployment generator copies these values into
# the topology record of any deployment that runs the image.
#
# Image construction delegates to sb_image_build on the bound backend so that this script remains
# independent of any specific container runtime.

SELF="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
# shellcheck source=SCRIPTDIR/../lib/common.sh
. "$SELF/../lib/common.sh"
# shellcheck source=SCRIPTDIR/../lib/backend/contract.sh
. "$SELF/../lib/backend/contract.sh"

set -euo pipefail

# Do not enable px_trap_enable because command substitutions in this script intentionally return
# expected non-zero exit statuses.

# Path to the build record generated by build-phoenix.sh, relative to the output root.
SA_RECORD_REL=build/phoenix/build.tsv

# Core distributions required by the image and optional profiling tools included whenever the
# version definitions list them.
SA_REQUIRED_DISTS="hbase hadoop"
SA_TOOL_DISTS="async-profiler"

# Regular expression matching a PX_* build argument declaration line in the image definition.
SA_ARG_RE='^ARG[[:space:]]+(PX_[A-Za-z0-9_]+)(=.*)?$'

# Regular expression matching a valid base image digest consisting of 64 lowercase hexadecimal
# digits with an optional sha256: prefix.
SA_DIGEST_RE='^(sha256:)?([0-9a-f]{64})$'

SA_TAG=""
SA_STAGE_ONLY=0
SA_RECORD=""
SA_CTX=""
SA_EXPECTED=""
SA_FAILS=0
SA_BUILD_ARGS=()
SA_ROWS=""
SA_ARCH=""
SA_ARCH_KEY=""
# Path to the file persisting trust-on-first-use base image digests.
SA_PINS=""
# Newline-separated entry listing from the archive most recently processed by sa_stage_archive.
SA_LISTING=""
# Accumulated PX_STAGED_* build arguments formatted as tab-separated NAME and VALUE rows.
SA_STAGED=""
# Release versions of the ZooKeeper and Hadoop client JARs bundled in the HBase lib/ directory.
SA_ZOOKEEPER=""
SA_HBASE_HADOOP=""

## @description  Prints the command-line usage documentation and available options.
## @return       Writes the help message to standard output and exits with status 0.
usage() {
  cat <<'EOF'
Usage: stage-artifacts.sh [option...]

Stages the image build context under $PX_OUT/images/<context>/ from the image
directory, the verified distributions and the recorded Phoenix jars, runs
the staging checks, writes the staging record
$PX_OUT/images/<context>.staged.tsv, and builds the image through the
substrate contract. Run build-phoenix.sh first.

Options:
  --tag TAG           the image tag, default PX_IMAGE_TAG
  --stage-only        stage and check, and build nothing
  -n, --dry-run       report the plan and change nothing
  --config FILE       an extra configuration file, repeatable
  -v, --verbose       report detail
  -h, --help          show this text

stdout: the image row of the build, tag and image id. With --stage-only, one
row: context and the context directory.

Exit codes: 0 ok, 1 a staging check or the build failed, 2 usage, or an HBase
release outside the range of the profile, 4 the build expired, 5 the backend
cannot build an image, 6 no build record or no image
directory. Any status of fetch-dist.sh passes through.
EOF
}

## @description  Looks up and prints the value associated with a single key in the build record.
## @return       Writes the value to stdout and returns 0, or returns 6 if the key is absent.
sa_record_get() { px_tsv_get "$1" "$SA_RECORD"; }

## @description  Logs a failed staging check and increments the failure count so all checks can
##               run and report their results together.
## @return       Always returns 0.
sa_fail() {
  px_error "staging check failed: $*"
  SA_FAILS=$((SA_FAILS + 1))
}

# Copies a file from its source path to the relative context path and verifies its presence and
# byte-level integrity, requiring non-empty content when the kind is artifact rather than image.
## @description  Stages and validates one file given its source path, context path, and kind.
## @return       Returns 0, or terminates the process with status 1 if directory creation fails.
sa_stage() {
  local src=$1 rel=$2 kind=${3:-artifact}
  SA_EXPECTED="$SA_EXPECTED$rel$PX_NL"
  if [ ! -f "$src" ] || { [ "$kind" = artifact ] && [ ! -s "$src" ]; }; then
    sa_fail "presence: $src is absent or empty"
    return 0
  fi
  mkdir -p "$SA_CTX/$(dirname "$rel")"
  if ! cp -p "$src" "$SA_CTX/$rel"; then
    sa_fail "presence: cannot copy $src to $rel"
    return 0
  fi
  if ! cmp -s "$src" "$SA_CTX/$rel"; then
    sa_fail "integrity: $rel differs from $src"
  fi
}

## @description  Stages a gzip tar archive under dist/, captures its listing, and binds it to the
##               given build argument.
## @return       Returns 0, or terminates the process with status 1 if directory creation fails.
sa_stage_archive() {
  local archive=$1 arg=$2 rel
  SA_LISTING=""
  case "$archive" in
  *.tar.gz | *.tgz) ;;
  *)
    sa_fail "presence: $archive is not a gzip tar archive, which the image unpacks"
    return 0
    ;;
  esac
  rel="dist/${archive##*/}"
  sa_stage "$archive" "$rel"
  if [ -f "$SA_CTX/$rel" ] && ! SA_LISTING="$(tar -tzf "$SA_CTX/$rel" 2>/dev/null)"; then
    sa_fail "integrity: $rel does not list as a gzip tar archive"
  fi
  SA_STAGED="$SA_STAGED$arg$PX_TAB$rel$PX_NL"
}

# Extracts the release version from the single lib/<name>-<release>.jar entry in the staged HBase
# archive listing and assigns it to the named target variable.
## @description  Resolves the release version of a single bundled HBase JAR into a target variable.
## @return       Returns 0, or records a versions check failure if zero or multiple JARs match.
sa_shipped() {
  local name=$1 hits
  hits="$(printf '%s\n' "$SA_LISTING" |
    grep -E "^[^/]+/lib/$name-[0-9]+(\.[0-9]+)*\.jar\$" || true)"
  case "$hits" in
  '') sa_fail "versions: the hbase distribution ships no lib/$name-<release>.jar" ;;
  *"$PX_NL"*)
    sa_fail "versions: the hbase distribution ships more than one" \
      "lib/$name-<release>.jar: ${hits//$PX_NL/ }"
    ;;
  *)
    hits=${hits##*/"$name"-}
    printf -v "$2" '%s' "${hits%.jar}"
    ;;
  esac
}

## @description  Checks whether a context-relative file path belongs to the expected staging set.
## @return       Returns 0 when the path is in the expected set, or 1 otherwise.
sa_expected() {
  case "$PX_NL$SA_EXPECTED" in
  *"$PX_NL$1$PX_NL"*) return 0 ;;
  esac
  return 1
}

## @description  Scans the build context and flags any path not accounted for by a staging source.
## @return       Always returns 0, recording each stray or invalid file through sa_fail.
sa_check_strays() {
  local path rel base
  while IFS= read -r path; do
    [ -n "$path" ] || continue
    rel=${path#"$SA_CTX"/}
    base=${rel##*/}
    if [ -L "$path" ] || [ ! -f "$path" ]; then
      sa_fail "strays: $rel is not a regular file"
      continue
    fi
    case "$rel" in
    .dockerignore) ;;
    .* | */.*) sa_fail "strays: $rel is a hidden file"; continue ;;
    esac
    case "$base" in
    *~ | *.swp | *.swo | *.bak | *.orig | *.rej | '#'*'#')
      sa_fail "strays: $rel is a backup or editor file"
      continue
      ;;
    esac
    if ! sa_expected "$rel"; then
      sa_fail "strays: $rel comes from no staging source"
    fi
  done <<EOF
$(find "$SA_CTX" ! -type d -print 2>/dev/null | LC_ALL=C sort)
EOF
}

## @description  Verifies across a source tree and a list of JARs that no source file is newer
##               than the oldest staged JAR.
## @return       Always returns 0, recording any freshness violation through sa_fail.
sa_check_fresh() {
  local tree=$1 oldest="" jar newer
  shift
  for jar in "$@"; do
    [ -f "$jar" ] || continue
    if [ -z "$oldest" ] || [ "$jar" -ot "$oldest" ]; then
      oldest=$jar
    fi
  done
  [ -n "$oldest" ] || return 0
  # Ignore the exit status of find so that an unreadable directory cannot mask newer source files
  # discovered elsewhere in the tree.
  newer="$({ find "$tree" \( -path "$tree/dev" -o -name target -o -name .git \) -prune -o \
    -type f \( -name pom.xml -o -path '*/src/main/*' \) -newer "$oldest" -print \
    2>/dev/null || true; } | sed -n 1p)"
  if [ -n "$newer" ]; then
    sa_fail "freshness: the SNAPSHOT jar $oldest is older than $newer." \
      "Run build-phoenix.sh again."
  fi
}

## @description  Computes and prints the value for a script-managed build argument, which may be
##               empty.
## @return       Writes the value and returns 0, or returns 6 for an unowned name or missing key.
sa_computed_arg() {
  local name=$1 pin value
  case "$name" in
  PX_UID) id -u ;;
  PX_GID) id -g ;;
  PX_ARCH) printf '%s\n' "$SA_ARCH" ;;
  PX_PHOENIX_VERSION) sa_record_get phoenix_version ;;
  PX_HBASE_VERSION) printf '%s\n' "${PX_DIST_HBASE_VERSION:-}" ;;
  PX_HADOOP_VERSION) printf '%s\n' "${PX_DIST_HADOOP_VERSION:-}" ;;
  PX_ZOOKEEPER_VERSION) printf '%s\n' "$SA_ZOOKEEPER" ;;
  PX_HBASE_HADOOP_VERSION) printf '%s\n' "$SA_HBASE_HADOOP" ;;
  PX_STAGED_*) px_tsv_get "$name" "$SA_STAGED" || true ;;
  PX_IMAGE_BASE_JDK*_SHA256)
    pin="${name}_$SA_ARCH_KEY"
    value="${!pin:-$(sa_base_digest "$pin" "${name%_SHA256}")}"
    [[ $value =~ $SA_DIGEST_RE ]] || return 0
    printf '%s\n' "${BASH_REMATCH[2]}"
    ;;
  *) return "$PX_EXIT_NO_OBJECT" ;;
  esac
}

# Resolves the digest for an unpinned base image identified by its pin variable name and base image
# variable name, returning the previously recorded trust-on-first-use value or querying the backend
# to resolve and persist the digest when performing an actual image build.
## @description  Resolves the digest of an unpinned base image from the pin file or the backend.
## @return       Writes the resolved digest (or nothing if unavailable) to stdout and returns 0.
sa_base_digest() {
  local pin=$1 base=$2 line value="" row
  if [ -f "$SA_PINS" ]; then
    while IFS= read -r line || [ -n "$line" ]; do
      case "$line" in
      "$pin="*) value=${line#*=} ;;
      esac
    done <"$SA_PINS"
  fi
  if [ -z "$value" ] && [ "$SA_STAGE_ONLY" = 0 ] && [ -n "${!base:-}" ] &&
    row="$(sb_call sb_image_base_digest "${!base}" "$SA_ARCH")"; then
    value="$(px_tsv_field 2 "$row")"
    printf '%s=%s\n' "$pin" "$value" >>"$SA_PINS" ||
      px_warn "cannot record the digest of ${!base} in $SA_PINS"
    px_warn "trust on first use: the base image ${!base} ($SA_ARCH) has no declared" \
      "digest. Its digest $value is recorded in $SA_PINS and used from now on."
  fi
  printf '%s\n' "$value"
}

## @description  Populates SA_BUILD_ARGS for every PX_* ARG declared in a Dockerfile and records a
##               presence failure when a required argument has no value.
## @return       Always returns 0, recording any missing argument value through sa_fail.
sa_collect_args() {
  local file=$1 line name value seen=" " computed
  while IFS= read -r line || [ -n "$line" ]; do
    px_trim_var line
    [[ $line =~ $SA_ARG_RE ]] || continue
    name=${BASH_REMATCH[1]}
    computed=${BASH_REMATCH[2]}
    case "$seen" in
    *" $name "*) continue ;;
    esac
    seen="$seen$name "
    value="$(sa_computed_arg "$name")" || value="${!name:-}"
    if [ -n "$value" ]; then
      SA_BUILD_ARGS+=("$name=$value")
    elif [ -z "$computed" ]; then
      case "$name" in
      PX_IMAGE_BASE_JDK*_SHA256)
        sa_fail "presence: the image declares the build argument $name, and" \
          "${name}_$SA_ARCH_KEY holds no digest of 64 hexadecimal digits. A build" \
          "without --stage-only records it on first use in $SA_PINS when the" \
          "registry answers, or record it in versions.local.env"
        ;;
      *)
        sa_fail "presence: the image declares the build argument $name, and no" \
          "configuration value sets it"
        ;;
      esac
    fi
  done <"$file"
}

while [ $# -gt 0 ]; do
  px_cli_common "$1" || case "$1" in
  --tag) px_cli_need_value "$@" && SA_TAG="$2" && shift ;;
  --stage-only) SA_STAGE_ONLY=1 ;;
  --config) px_cli_need_value "$@" && SA_CONFIG_FILES+=("$2") && shift ;;
  -*) px_usage_error "unknown option: $1" ;;
  *) px_usage_error "unexpected argument: $1" ;;
  esac
  shift
done

px_config_load -- ${SA_CONFIG_FILES[@]+"${SA_CONFIG_FILES[@]}"}
px_versions_check

SA_TAG="${SA_TAG:-${PX_IMAGE_TAG:-}}"
if ! sb_image_tag_local "$SA_TAG"; then
  px_usage_error "the image tag '$SA_TAG' is not a local repository:tag; set PX_IMAGE_TAG" \
    "or --tag"
fi

SA_ROOT="$(px_out_root)" || exit $?
SA_RECORD_FILE="$SA_ROOT/$SA_RECORD_REL"
if [ ! -f "$SA_RECORD_FILE" ]; then
  px_die "$PX_EXIT_NO_OBJECT" "no build record at $SA_RECORD_FILE. Run build-phoenix.sh first."
fi
SA_RECORD="$(cat "$SA_RECORD_FILE")"
for SA_KEY in tree phoenix_version hbase_profile compat_module hbase_version hadoop_version \
  server_jar client_jar pherf_jar; do
  if ! sa_record_get "$SA_KEY" >/dev/null; then
    px_die "$PX_EXIT_FAIL" "the build record $SA_RECORD_FILE has no $SA_KEY." \
      "Run build-phoenix.sh again."
  fi
done
SA_TREE="$(sa_record_get tree)"
SA_PHOENIX_VERSION="$(sa_record_get phoenix_version)"
SA_PROFILE="$(sa_record_get hbase_profile)"

SA_IMAGE_DIR="$PX_HOME/$PX_DEPLOY_SUBDIR/image"
SA_IGNORE="$PX_HOME/$PX_DEPLOY_SUBDIR/.dockerignore"
if [ ! -f "$SA_IMAGE_DIR/Dockerfile" ]; then
  px_die "$PX_EXIT_NO_OBJECT" "no image definition at $SA_IMAGE_DIR/Dockerfile"
fi

# Assemble the list of distributions to stage by combining the required core distributions with
# any optional tool distributions enabled in the version definitions.
SA_DISTS=()
for SA_NAME in $SA_REQUIRED_DISTS; do
  SA_DISTS+=("$SA_NAME")
done
for SA_NAME in $SA_TOOL_DISTS; do
  case " ${PX_DIST_ARTIFACTS//,/ } " in
  *" $SA_NAME "*) SA_DISTS+=("$SA_NAME") ;;
  esac
done

if px_is_dry_run; then
  px_info "dry run: would stage Phoenix $SA_PHOENIX_VERSION of profile $SA_PROFILE for HBase" \
    "$PX_DIST_HBASE_VERSION and Hadoop $PX_DIST_HADOOP_VERSION from $SA_IMAGE_DIR, the" \
    "distributions ${SA_DISTS[*]} and the jars of" \
    "$SA_RECORD_FILE under $SA_ROOT/images, then build the image $SA_TAG"
  exit 0
fi

# Retrieve and verify all selected distributions before modifying the build context. Cached files
# that already match their declared pins require no network transfer. After stripping the leading
# distribution name, each returned row contains the architecture, version, file path, calculated
# SHA-512 checksum, and pinned checksum.
SA_STATUS=0
SA_ROWS="$("$SELF/fetch-dist.sh" "${SA_DISTS[@]}")" || SA_STATUS=$?
if [ "$SA_STATUS" != 0 ]; then
  px_die "$SA_STATUS" "the distributions could not be retrieved and verified"
fi
SA_ROW="$(px_tsv_get hbase "$SA_ROWS")" ||
  px_die "$PX_EXIT_FAIL" "fetch-dist.sh reported no hbase distribution"
SA_ARCH="$(px_tsv_field 1 "$SA_ROW")"
SA_ARCH_KEY="$(px_upper "$SA_ARCH")"
if [ "$SA_ARCH" = amd64 ]; then
  px_warn "the image is built for amd64, which is best effort. arm64 is the primary" \
    "architecture and the one the harness proves."
fi

SA_IMAGES="$(px_out_subdir images)" || exit $?
SA_PINS="$SA_IMAGES/pins.env"
SA_CTX="$SA_IMAGES/$(px_image_stage_name "$SA_TAG")"
rm -rf "$SA_CTX" "$SA_CTX.staged.tsv"
mkdir -p "$SA_CTX/dist" "$SA_CTX/phoenix" ||
  px_die "$PX_EXIT_FAIL" "cannot create the build context $SA_CTX"
px_info "staging the build context $SA_CTX"

# Stage the layout image directory. The initial recursive copy preserves any empty directories that
# the image definition expects to copy and keeps symbolic links intact so that the stray-file check
# can detect and report them. The subsequent file loop populates the expected file set and verifies
# every regular file individually.
cp -RP "$SA_IMAGE_DIR/." "$SA_CTX/" || sa_fail "presence: cannot copy $SA_IMAGE_DIR"
while IFS= read -r SA_PATH; do
  [ -n "$SA_PATH" ] || continue
  sa_stage "$SA_PATH" "${SA_PATH#"$SA_IMAGE_DIR"/}" image
done <<EOF
$(find "$SA_IMAGE_DIR" -type f 2>/dev/null | LC_ALL=C sort)
EOF
if [ -f "$SA_IGNORE" ]; then
  sa_stage "$SA_IGNORE" .dockerignore image
fi

# Stage the distribution archives, each of which was just verified against its declared pin.
for SA_NAME in "${SA_DISTS[@]}"; do
  SA_ROW="$(px_tsv_get "$SA_NAME" "$SA_ROWS")" || continue
  SA_PATH="$(px_tsv_field 3 "$SA_ROW")"
  sa_stage_archive "$SA_PATH" "PX_STAGED_$(px_upper "$SA_NAME")"
  # Because the HBase daemons and the ZooKeeper server execute using the JARs bundled inside the
  # HBase distribution, their release versions are derived directly from the archive listing rather
  # than from external configuration properties.
  if [ "$SA_NAME" = hbase ] && [ -n "$SA_LISTING" ]; then
    sa_shipped zookeeper SA_ZOOKEEPER
    sa_shipped hadoop-common SA_HBASE_HADOOP
  fi
done
# Reject a build record compiled for a different HBase profile because its JARs target a different
# compatibility module.
if [ "$SA_PROFILE" != "$PX_PHOENIX_HBASE_PROFILE" ]; then
  sa_fail "versions: the build record is of the HBase profile $SA_PROFILE, and" \
    "PX_PHOENIX_HBASE_PROFILE is $PX_PHOENIX_HBASE_PROFILE. Run build-phoenix.sh again."
fi

# Stage the Phoenix JARs listed in the build record.
SA_JARS=()
for SA_KEY in server_jar client_jar pherf_jar distributed_jar; do
  SA_PATH="$(sa_record_get "$SA_KEY")" || continue
  sa_stage "$SA_PATH" "phoenix/${SA_PATH##*/}"
  SA_ARG="PX_STAGED_PHOENIX_$(px_upper "${SA_KEY%_jar}")"
  SA_STAGED="$SA_STAGED$SA_ARG${PX_TAB}phoenix/${SA_PATH##*/}$PX_NL"
  SA_JARS+=("$SA_PATH")
done
case "$SA_PHOENIX_VERSION" in
*-SNAPSHOT) sa_check_fresh "$SA_TREE" "${SA_JARS[@]}" ;;
esac
sa_check_strays
# Bind the backend before collecting build arguments because argument resolution may need to query
# the backend for an unpinned base image digest. Container images are always built against the
# local container engine driven by the Compose backend, after which px-cluster build imports them
# into px-k3d when targeting Kubernetes.
sb_load compose
sa_collect_args "$SA_IMAGE_DIR/Dockerfile"

if [ "$SA_FAILS" -gt 0 ]; then
  px_die "$PX_EXIT_FAIL" "$SA_FAILS staging check(s) failed, the image is not built"
fi
px_info "the staging checks passed for $SA_CTX"
# Persist the staging record describing the complete version set of the build context. Any
# deployment that uses this image reads the bundled ZooKeeper and Hadoop client versions from this
# file.
SA_STAGED_RECORD="$SA_CTX.staged.tsv"
{
  px_tsv_row image_tag "$SA_TAG"
  px_tsv_row hbase_profile "$SA_PROFILE"
  px_tsv_row compat_module "$(sa_record_get compat_module)"
  px_tsv_row hbase_version "$PX_DIST_HBASE_VERSION"
  px_tsv_row hadoop_version "$PX_DIST_HADOOP_VERSION"
  px_tsv_row zookeeper_version "$SA_ZOOKEEPER"
  px_tsv_row hbase_hadoop_version "$SA_HBASE_HADOOP"
  px_tsv_row arch "$SA_ARCH"
} >"$SA_STAGED_RECORD" || px_die "$PX_EXIT_FAIL" "cannot write $SA_STAGED_RECORD"
if [ "$SA_STAGE_ONLY" = 1 ]; then
  px_tsv_row context "$SA_CTX"
  exit 0
fi

px_debug "build arguments: ${SA_BUILD_ARGS[*]}"
SA_STATUS=0
sb_call sb_image_build "$SA_CTX" "$SA_TAG" ${SA_BUILD_ARGS[@]+"${SA_BUILD_ARGS[@]}"} ||
  SA_STATUS=$?
case "$SA_STATUS" in
0) px_info "built the image $SA_TAG from $SA_CTX" ;;
"$PX_EXIT_UNSUPPORTED")
  px_die "$PX_EXIT_UNSUPPORTED" "the local engine cannot build an image"
  ;;
*) px_die "$SA_STATUS" "the image build of $SA_TAG failed" ;;
esac
