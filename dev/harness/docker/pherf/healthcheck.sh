# Health probe for a single Distributed Pherf process running inside the pherf container image:
#   controller  Issues a single GET /v1/agents request to the REST port PHERF_REST_PORT (default
#               8780) at PHERF_BIND_ADDRESS (default 127.0.0.1).
#   agent       Runs the launch script liveness check (agent status) and then sends one request to
#               the agent channel endpoint of PHERF_CONTROLLER, where any HTTP response (including
#               405) confirms the network path and an active listener.
# Each probe execution performs a single check and never retries internally; the deployment
# configures the probe interval, retry count, and startup grace period. The standalone Compose
# file, the Compose file generated by the harness, and the Kubernetes probes all execute this
# script so that role health is governed by a single uniform rule across every substrate.
# Because a healthy agent process may not yet be registered with the controller, fleet readiness
# is determined when GET /v1/agents lists the expected agent count; startup routines that wait for
# the fleet wait on that registered count rather than on agent container health.
#
# Exit codes: 0 when healthy; otherwise the exit status of curl or of pherf-distributed.sh agent
# status (3 when not running, 2 on configuration error); or 2 on invalid usage or when
# PHERF_CONTROLLER is unset.

set -euo pipefail

## @description  Prints the command-line usage message to standard error and terminates.
## @return       Exits with usage status 2.
usage() {
  echo "usage: healthcheck.sh controller|agent" >&2
  exit 2
}

[ $# -eq 1 ] || usage
case "$1" in
controller)
  host="${PHERF_BIND_ADDRESS:-127.0.0.1}"
  case "$host" in
  *:*) host="[$host]" ;;
  esac
  exec curl -fsS --noproxy '*' -o /dev/null --max-time 5 \
    "http://$host:${PHERF_REST_PORT:-8780}/v1/agents"
  ;;
agent)
  [ -n "${PHERF_CONTROLLER:-}" ] || { echo "PHERF_CONTROLLER is not set" >&2; exit 2; }
  pherf-distributed.sh agent status >/dev/null
  exec curl -sS --noproxy '*' -o /dev/null --max-time 5 "${PHERF_CONTROLLER%/}/v1/channel/"
  ;;
*) usage ;;
esac
